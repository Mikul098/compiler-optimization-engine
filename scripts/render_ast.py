"""
==============================================================================
File: scripts/render_ast.py
Purpose: Visual AST graph generator using Matplotlib.

Role in Compiler:
 - Visualization tool invoked by main.cpp (or run standalone via CLI).
 - Ingests the 'ast.json' hierarchy generated by the compiler during parsing.
 - Computes recursive (x, y) tree coordinates with child spacing and depth layers.
 - Draws styled, color-coded node badges and directed edges for:
     * Program root (Indigo)
     * Assignments (Blue)
     * Print statements (Green)
     * Binary operations (Amber)
     * Variable references (Cyan)
     * Number literals (Rose)
 - Renders and saves a clean high-resolution graphical diagram to 'ast.png'.
==============================================================================
"""

import json
import matplotlib.pyplot as plt
import os
import sys

# Color scheme for node types
COLORS = {
    "root": "#6366f1",    # Indigo
    "assign": "#0284c7",  # Blue
    "print": "#059669",   # Green
    "op": "#d97706",      # Amber
    "var": "#0891b2",     # Cyan
    "num": "#e11d48",     # Rose
}

def layout_tree(node, depth=0, next_x=[0]):
    """Assign (x, y) coordinates to tree nodes so children are spaced nicely."""
    children = node.get("children", [])
    child_coords = []
    for child in children:
        child_coords.append(layout_tree(child, depth + 1, next_x))
    
    if child_coords:
        x = sum(c[0] for c in child_coords) / len(child_coords)
    else:
        x = next_x[0]
        next_x[0] += 1.6
        
    y = -depth * 1.5
    node["pos"] = (x, y)
    return (x, y)

def draw_tree(node, ax):
    x, y = node["pos"]
    node_type = node.get("type", "root")
    color = COLORS.get(node_type, "#475569")
    label = node.get("name", "")

    # Draw connection to children
    for child in node.get("children", []):
        cx, cy = child["pos"]
        edge_label = child.get("edge", "")
        
        # Draw curve/arrow line
        ax.annotate(
            "",
            xy=(cx, cy + 0.35),
            xytext=(x, y - 0.35),
            arrowprops=dict(
                arrowstyle="-|>",
                color="#64748b",
                lw=2,
                shrinkA=0,
                shrinkB=0,
                mutation_scale=15
            )
        )
        
        # Edge label (e.g. Left / Right)
        if edge_label:
            mid_x = (x + cx) / 2
            mid_y = (y + cy) / 2
            ax.text(
                mid_x, mid_y, edge_label,
                color="#38bdf8" if edge_label == "Left" else "#f472b6",
                fontsize=9,
                fontweight="bold",
                ha="center",
                va="center",
                bbox=dict(boxstyle="round,pad=0.2", facecolor="#0f172a", edgecolor="none", alpha=0.9)
            )
        
        draw_tree(child, ax)

    # Draw current node box
    ax.text(
        x, y, label,
        color="#ffffff",
        fontsize=10.5,
        fontweight="bold",
        ha="center",
        va="center",
        bbox=dict(
            boxstyle="round,pad=0.5,rounding_size=0.4",
            facecolor=color,
            edgecolor="#ffffff",
            linewidth=1.2,
            alpha=0.95
        )
    )

def render(json_file="ast.json", output_png="ast.png"):
    if not os.path.exists(json_file):
        return
    with open(json_file, "r") as f:
        data = json.load(f)

    next_x = [0]
    layout_tree(data, 0, next_x)

    fig, ax = plt.subplots(figsize=(max(10, next_x[0] * 1.2), 8), facecolor="#0f172a")
    ax.set_facecolor("#0f172a")
    ax.axis("off")

    draw_tree(data, ax)

    # Add Title
    ax.set_title("Abstract Syntax Tree (AST)", color="#38bdf8", fontsize=16, fontweight="bold", pad=20)

    # Calculate padding bounds
    all_x = []
    all_y = []
    def collect_coords(n):
        all_x.append(n["pos"][0])
        all_y.append(n["pos"][1])
        for c in n.get("children", []):
            collect_coords(c)
    collect_coords(data)

    ax.set_xlim(min(all_x) - 1.2, max(all_x) + 1.2)
    ax.set_ylim(min(all_y) - 1.0, max(all_y) + 1.0)

    plt.tight_layout()
    plt.savefig(output_png, dpi=200, bbox_inches="tight", facecolor="#0f172a")
    plt.close()
    print(f"AST Image successfully saved to: {output_png}")

if __name__ == "__main__":
    json_path = sys.argv[1] if len(sys.argv) > 1 else "ast.json"
    png_path = sys.argv[2] if len(sys.argv) > 2 else "ast.png"
    render(json_path, png_path)
